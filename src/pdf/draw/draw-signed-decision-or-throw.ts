import type { PDFDocument } from 'pdf-lib'
import type { SignRecord } from '../types'
import type { Writer } from '../writer'

export const drawSignedDecisionOrThrow = async (doc: PDFDocument, w: Writer, rec: SignRecord, signature: Uint8Array) => {
  w.rule()
  w.text(`Decision: ${rec.decision === 'approved' ? 'Approved' : 'Declined'}`, { size: 14, bold: true })

  if (rec.reason) w.text(`Reason: ${rec.reason}`)

  w.text(`Signer: ${rec.signer_name}`)
  w.image(await doc.embedPng(signature), 220, 80)
  w.text(`Signed at (UTC): ${rec.signed_at}`, { size: 9 })
  w.text(`IP address: ${rec.ip || 'unknown'}`, { size: 9 })
  w.text(`User agent: ${rec.user_agent || 'unknown'}`, { size: 9 })
  w.text(`Snapshot SHA-256: ${rec.snapshot_sha256}`, { size: 9, gap: 12 })
  w.text(`Electronic signature record generated by ${rec.product}. Verify at ${rec.verify_url}`, { size: 9 })
}
